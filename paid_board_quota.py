"""Internal paid Board Sense quota foundation. NOT connected to public paid access.

Only trusted backend code may call these functions with a customer UUID already
verified by the identity provider. Subscription states here are assumed to come
from the *future* verified production payment reconciler, never from the PayPal
sandbox pilot, customer input, or a browser return URL.

No HTTP endpoints are exported. Board Sense must not use this until a secured
cross-service authorization protocol and failure policy have been tested.
"""
from __future__ import annotations

from contextlib import closing
from dataclasses import dataclass
from datetime import datetime, timezone
from uuid import UUID

from membership_catalog import PLANS
from membership_records import connect as membership_connect

DAILY_PAID_BOARD_LIMIT = 25
KNOWN_MODULES = frozenset(("board_sense", "scrap_radar"))


@dataclass(frozen=True)
class QuotaResult:
    allowed: bool
    reason: str
    day_utc: str
    used_today: int
    limit: int = DAILY_PAID_BOARD_LIMIT

    @property
    def remaining(self) -> int:
        return max(0, self.limit - self.used_today)


def _uuid(value: str, field: str) -> str:
    try:
        return str(UUID(value))
    except (ValueError, AttributeError, TypeError):
        raise ValueError(f"{field} must be a valid UUID") from None


def _day(now: datetime | None) -> str:
    moment = datetime.now(timezone.utc) if now is None else now
    if not isinstance(moment, datetime) or moment.tzinfo is None or moment.utcoffset() is None:
        raise ValueError("A timezone-aware datetime is required")
    return moment.astimezone(timezone.utc).date().isoformat()


def _connect():
    conn = membership_connect()
    conn.execute("""CREATE TABLE IF NOT EXISTS paid_board_case_ledger (
        case_id TEXT PRIMARY KEY,
        customer_id TEXT NOT NULL,
        day_utc TEXT NOT NULL,
        status TEXT NOT NULL CHECK(status IN ('RESERVED','COMPLETE','RELEASED')),
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    )""")
    conn.execute("""CREATE INDEX IF NOT EXISTS paid_board_case_customer_day
        ON paid_board_case_ledger (customer_id,day_utc,status)""")
    conn.commit()
    return conn


def _has_active_module(conn, customer_id: str, module: str) -> bool:
    # Only registered software modules qualify. Family future-module coverage
    # requires explicitly adding new modules to KNOWN_MODULES at release time.
    if module not in KNOWN_MODULES:
        return False
    rows = conn.execute("""SELECT plan_id,state FROM membership_records
        WHERE customer_id=?""", (customer_id,)).fetchall()
    for plan_id, state in rows:
        plan = PLANS.get(plan_id)
        if state == "ACTIVE" and plan and (
            module in plan["modules"] or (plan["future_family_modules"] and module in KNOWN_MODULES)
        ):
            return True
    return False


def has_reconciled_module(customer_id: str, module: str) -> bool:
    """Internal ledger eligibility, NOT a public paid-access authorization.

    The current sandbox has no path to production membership_records. A later
    integration must verify provider subscription state and current identity
    before any decision from this helper can become an access grant.
    """
    customer_id = _uuid(customer_id, "customer_id")
    with closing(_connect()) as conn:
        return _has_active_module(conn, customer_id, module)


def _used(conn, customer_id: str, day_utc: str) -> int:
    row = conn.execute("""SELECT COUNT(*) FROM paid_board_case_ledger
        WHERE customer_id=? AND day_utc=?
          AND status IN ('RESERVED','COMPLETE')""", (customer_id, day_utc)).fetchone()
    return int(row[0])


def paid_board_usage(customer_id: str, *, now: datetime | None = None) -> QuotaResult:
    """Non-consuming view. Current reset policy is UTC, subject to owner signoff."""
    customer_id = _uuid(customer_id, "customer_id")
    day_utc = _day(now)
    with closing(_connect()) as conn:
        used = _used(conn, customer_id, day_utc)
        eligible = _has_active_module(conn, customer_id, "board_sense")
        return QuotaResult(eligible and used < DAILY_PAID_BOARD_LIMIT,
                           "available" if eligible and used < DAILY_PAID_BOARD_LIMIT
                           else "daily_limit_reached" if eligible
                           else "no_reconciled_active_plan", day_utc, used)


def reserve_paid_board_case(
    customer_id: str,
    case_id: str,
    *,
    now: datetime | None = None,
) -> QuotaResult:
    """Atomically count ONE physical board case, regardless of photo count.

    `case_id` must be generated by the trusted server for this actual physical
    board case, not by a caller choosing arbitrary IDs. Repeated reservations
    are idempotently rejected as repeat processing (the caller must retrieve
    the original case result instead). A RELEASED case cannot be reactivated.
    """
    customer_id = _uuid(customer_id, "customer_id")
    case_id = _uuid(case_id, "case_id")
    day_utc = _day(now)
    with closing(_connect()) as conn, conn:
        conn.execute("BEGIN IMMEDIATE")
        used = _used(conn, customer_id, day_utc)
        if not _has_active_module(conn, customer_id, "board_sense"):
            return QuotaResult(False, "no_reconciled_active_plan", day_utc, used)
        existing = conn.execute("""SELECT customer_id,day_utc,status
            FROM paid_board_case_ledger WHERE case_id=?""", (case_id,)).fetchone()
        if existing:
            if existing[0] != customer_id:
                raise ValueError("The case ID is already bound to another account")
            # Never grant another analysis for a reservation already running or
            # completed. Returning allowed=True would permit unlimited scans
            # using the same ID without consuming additional daily cases.
            # The future cross-service route should look up/poll the original
            # case result instead of calling the analyzer again.
            if existing[1] != day_utc:
                reason = "case_previous_day"
            elif existing[2] == "RESERVED":
                reason = "already_reserved"
            elif existing[2] == "COMPLETE":
                reason = "already_completed"
            else:
                reason = "case_released"
            return QuotaResult(False, reason, day_utc, used)
        if used >= DAILY_PAID_BOARD_LIMIT:
            return QuotaResult(False, "daily_limit_reached", day_utc, used)
        conn.execute("""INSERT INTO paid_board_case_ledger
            (case_id,customer_id,day_utc,status) VALUES (?,?,?,'RESERVED')""",
            (case_id, customer_id, day_utc))
        return QuotaResult(True, "reserved", day_utc, used + 1)


def _transition(customer_id: str, case_id: str, source: str, destination: str) -> bool:
    customer_id = _uuid(customer_id, "customer_id")
    case_id = _uuid(case_id, "case_id")
    with closing(_connect()) as conn, conn:
        conn.execute("BEGIN IMMEDIATE")
        row = conn.execute("""SELECT customer_id,status FROM paid_board_case_ledger
            WHERE case_id=?""", (case_id,)).fetchone()
        if row is None or row[0] != customer_id:
            return False
        if row[1] == destination:
            return True
        if row[1] != source:
            return False
        conn.execute("""UPDATE paid_board_case_ledger
            SET status=?,updated_at=CURRENT_TIMESTAMP WHERE case_id=?""",
            (destination, case_id))
        return True


def finish_paid_board_case(customer_id: str, case_id: str) -> bool:
    """Mark a completed analysis once; never release a completed case."""
    return _transition(customer_id, case_id, "RESERVED", "COMPLETE")


def release_failed_paid_board_case(customer_id: str, case_id: str) -> bool:
    """Return a reservation only on a trusted server-side failure.

    This must NEVER be exposed as a customer-controlled refund endpoint or
    used for successful analyses. Existing released case IDs cannot be reused.
    """
    return _transition(customer_id, case_id, "RESERVED", "RELEASED")
